const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { create, verify, restore, safePath } = require('./audio-editing-snapshot.cjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'evd-snapshot-test-'));
const name = 'src/main/ffmpeg-handler.js';
const file = safePath(root, name);
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, 'baseline\r\n');
const backup = create(root, [name]);
assert.equal(verify(backup).files.length, 1);
fs.writeFileSync(file, 'changed\n');
assert.deepEqual(restore(backup, false, root).changed, [name]);
assert.equal(fs.readFileSync(file, 'utf8'), 'changed\n');
const restored = restore(backup, true, root);
assert.equal(fs.readFileSync(file, 'utf8'), 'baseline\r\n');
assert.equal(fs.readFileSync(path.join(restored.safetyBackup, 'files', name), 'utf8'), 'changed\n');
assert.deepEqual(restore(backup, false, root).changed, []);
assert.throws(() => safePath(root, '../outside'));
assert.throws(() => safePath(root, 'C:/outside'));
fs.writeFileSync(path.join(backup, 'files', name), 'corrupt');
assert.throws(() => restore(backup, true, root), /verification failed/);
assert.equal(fs.readFileSync(file, 'utf8'), 'baseline\r\n');
console.log('PASS: hashes, dry run, restore, safety backup, path checks, corrupt backup rejection');
console.log(`Test fixture retained: ${root}`);
